function findEmployeeById(query) {
    if (!query) return null;
    const clean = query.toString().trim().toLowerCase();
    if (!clean) return null;
    let emp = EMPLOYEE_DATABASE.find(e => e.id && e.id.toString().trim().toLowerCase() === clean);
    if (emp) return emp;
    const numClean = clean.replace(/\D/g, '');
    if (numClean) {
        emp = EMPLOYEE_DATABASE.find(e => e.id && e.id.toString().trim() === numClean);
        if (emp) return emp;
    }
    emp = EMPLOYEE_DATABASE.find(e => e.fullName && e.fullName.toLowerCase().includes(clean));
    return emp || null;
}